-- ENUMS
CREATE TYPE notification_type AS ENUM (
    'info',
    'warning',
    'error',
    'success'
);

CREATE TYPE log_level AS ENUM (
    'info',
    'success',
    'warn',
    'error'
);

CREATE TYPE log_source AS ENUM (
    'system',
    'queue',
    'sensor',
    'smart_module',
    'auth'
);

CREATE TYPE log_event_type AS ENUM (
    'printer_connected',
    'printer_disconnected',
    'print_started',
    'print_completed',
    'print_failed',
    'low_resin',
    'robot_connected',
    'robot_disconnected',
    'task_started',
    'task_completed',
    'task_failed',
    'task_paused',
    'task_resumed'
);

CREATE TYPE user_role AS ENUM (
    'user',
    'admin'
);

CREATE TYPE print_job_status AS ENUM (
    'queued',
    'printing',
    'paused',
    'completed',
    'failed',
    'cancelled'
);

CREATE TYPE printer_status AS ENUM (
    'idle',
    'printing',
    'paused',
    'offline',
    'error',
    'maintenance'
);

CREATE TYPE build_plate_status AS ENUM (
    'ready',
    'in_use',
    'cleaning',
    'damaged'
);

CREATE TYPE robot_arm_queue_status AS ENUM (
    'queued',
    'active',
    'paused',
    'completed',
    'failed',
    'cancelled'
);

CREATE TYPE robot_arm_connection_status AS ENUM (
    'connected',
    'disconnected',
    'error'
);

CREATE TYPE robot_arm_operational_status AS ENUM (
    'idle',
    'active',
    'paused',
    'error'
);

-- TABLES
CREATE TABLE "user" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    role user_role NOT NULL
);

CREATE TABLE printer (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name UNIQUE text,
    model TEXT,
    status printer_status,
    location text,
    serialNumber text,
    lastMaintemamce text
    ipAddress text,
    sensorIp text,
    resinType text,
    resinLevel text,
    raspberryPiIp text,
    enableSensors BOOLEAN,
    smartModuleApiKeyEncrypted text
);

CREATE robot_arm (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name UNIQUE text,
    brand text,
    model text,
    serialNumber text,
    firmwareVersion text,
    ipAddress text,
    location text,
    connectionStatus robot_arm_connection_status,
    operationalStatus robot_arm_operational_status,
    lastSeenAt TIMESTAMP
);

CREATE TABLE print_job (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    printerId       integer REFERENCES printer(id),
    userId          integer REFERENCES "user"(id),
    fileName        text,
    filePath        text,
    fileSize        text,
    status          print_job_status,
    progress        integer,
    timeRemaining   INTERVAL,
    timeElapsed     INTERVAL,
    startedAt       TIMESTAMP,
    completedAt     text,
    queuePosition   integer,
    estimatedTime   text,
    material        text,
    currentLayer    integer,
    totalLayers    integer,
    volume          real,
    createdAt       TIMESTAMP,
    updatedAt       TIMESTAMP
);

CREATE TABLE build_plate (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    printerId   integer REFERENCES printer(id),
    location    text,
    status      build_plate_status,
    usageCount  integer,
    createdAt   TIMESTAMP,
    updatedAt   TIMESTAMP
);

CREATE TABLE notification (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    printerId   integer REFERENCES printer(id),
    printJobId  integer REFERENCES print_job(id),
    robotArmId  integer REFERENCES robot_arm(id),
    type        notification_type,
    title       text,
    message     text,
    read        integer,
    createdAt   TIMESTAMP,
    updatedAt   TIMESTAMP
);

CREATE TABLE log (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    printerId   integer REFERENCES printer(id),
    robotArmId  integer REFERENCES robot_arm(id),
    printJobId  integer REFERENCES print_job(id),
    level       log_level,
    source      log_source,
    message     text,
    eventType   log_event_type,
    createdAt   TIMESTAMP,
    updatedAt   TIMESTAMP
);

CREATE TABLE robot_arm_queue (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
);